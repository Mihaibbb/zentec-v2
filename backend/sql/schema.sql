-- MySQL schema for Medical Software App
CREATE DATABASE IF NOT EXISTS medical_app CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE medical_app;

CREATE TABLE IF NOT EXISTS clinics (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(191) NOT NULL,
  email VARCHAR(191) NOT NULL UNIQUE,
  location VARCHAR(191) NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(191) NOT NULL UNIQUE,
  password VARCHAR(191) NOT NULL,
  firstName VARCHAR(191) NOT NULL,
  lastName VARCHAR(191) NOT NULL,
  role ENUM('SUPER_ADMIN','ADMIN','DOCTOR') NOT NULL,
  clinicId INT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_clinic FOREIGN KEY (clinicId) REFERENCES clinics(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS doctors (
  id INT AUTO_INCREMENT PRIMARY KEY,
  userId INT NOT NULL UNIQUE,
  clinicId INT NOT NULL,
  color VARCHAR(20) NOT NULL DEFAULT '#F59E0B',
  CONSTRAINT fk_doctors_user FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_doctors_clinic FOREIGN KEY (clinicId) REFERENCES clinics(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS patients (
  id INT AUTO_INCREMENT PRIMARY KEY,
  clinicId INT NOT NULL,
  firstName VARCHAR(191) NOT NULL,
  lastName VARCHAR(191) NOT NULL,
  phone VARCHAR(50) NULL,
  notes TEXT NULL,
  email VARCHAR(191) NULL,
  country VARCHAR(191) NULL,
  city VARCHAR(191) NULL,
  address VARCHAR(191) NULL,
  gender ENUM('M','F','N') NULL,
  pic VARCHAR(64) NULL,
  fileNumber INT NULL,
  dob DATE NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_patients_clinic FOREIGN KEY (clinicId) REFERENCES clinics(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS appointments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  clinicId INT NOT NULL,
  doctorId INT NOT NULL,
  patientId INT NULL,
  title VARCHAR(191) NOT NULL,
  start DATETIME NOT NULL,
  end DATETIME NOT NULL,
  cost INT NOT NULL DEFAULT 0,
  notes TEXT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_appt_clinic FOREIGN KEY (clinicId) REFERENCES clinics(id) ON DELETE CASCADE,
  CONSTRAINT fk_appt_doctor FOREIGN KEY (doctorId) REFERENCES doctors(id) ON DELETE CASCADE,
  CONSTRAINT fk_appt_patient FOREIGN KEY (patientId) REFERENCES patients(id) ON DELETE SET NULL
);


